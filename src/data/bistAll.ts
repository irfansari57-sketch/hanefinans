/** Tekrar eden ticker'ları temizle (manuel listede duplicate olabilir). */
export const BIST_UNIQUE: BistStock[] = (() => {
  const seen = new Set<string>();
  return BIST_ALL.filter((s) => {
    if (seen.has(s.symbol)) return false;
    seen.add(s.symbol);
    return true;
  });
})();

export function findBistStock(symbol: string): BistStock | undefined {
  const s = symbol.toUpperCase();
  return BIST_UNIQUE.find((x) => x.symbol === s);
}
